"""Independent SNR monitor: actual output captures + direct RTL VCD verification.

Python standard library only. No noise is regenerated by this checker.
"""
import csv
import json
import math
from pathlib import Path
import struct
import sys

BUILD = Path.cwd()

def measure_rtl_vcd(path):
    scope, names, values = [], {}, {}
    required = ("i_clk", "o_valid", "o_clean_isi_data", "o_channel_data",
                "o_awgn_noise", "o_cfg_snr_db", "o_cfg_sigma_q12")
    identifiers = {}
    header = True
    previous_clock = 0
    signal = error = noise = count = 0

    def signed16(x):
        return x - 65536 if x >= 32768 else x

    def consume():
        nonlocal previous_clock, signal, error, noise, count
        clock = values.get(identifiers["i_clk"], 0)
        if not previous_clock and clock and values.get(identifiers["o_valid"], 0):
            clean = signed16(values[identifiers["o_clean_isi_data"]])
            output = signed16(values[identifiers["o_channel_data"]])
            injected = signed16(values[identifiers["o_awgn_noise"]])
            if output - clean != injected:
                raise RuntimeError("RTL VCD shows clipping or misaligned debug outputs")
            if values[identifiers["o_cfg_snr_db"]] != 20 or values[identifiers["o_cfg_sigma_q12"]] != 916:
                raise RuntimeError("RTL waveform configuration is not 20 dB / sigma_Q12=916")
            signal += clean*clean
            error += (output-clean)**2
            noise += injected*injected
            count += 1
        previous_clock = clock

    with path.open() as stream:
        for raw in stream:
            line = raw.strip()
            if header:
                fields = line.split()
                if line.startswith("$scope"):
                    scope.append(fields[2])
                elif line.startswith("$upscope"):
                    scope.pop()
                elif line.startswith("$var"):
                    names[".".join(scope+[fields[4]])] = fields[3]
                elif line.startswith("$enddefinitions"):
                    for name in required:
                        identifiers[name] = names["TOP."+name]
                    header = False
                continue
            if line.startswith("#"):
                consume()
            elif line.startswith("b"):
                bits, identifier = line[1:].split()
                if not any(c in bits for c in "xzXZ"):
                    values[identifier] = int(bits, 2)
            elif line and line[0] in "01":
                values[line[1:]] = int(line[0])
        consume()
    snr = 10*math.log10(signal/error)
    if count < 4000 or abs(snr-20) > .5:
        raise RuntimeError(f"SNR measured directly from RTL waveform failed: {count} samples, {snr:.4f} dB")
    return {"samples": count, "expected_db": 20, "measured_db": snr,
            "signal_power": signal/count/4096**2, "error_power": error/count/4096**2,
            "noise_power": noise/count/4096**2, "status": "PASS"}

waveform = measure_rtl_vcd(BUILD/"isi0_awgn.vcd")
(BUILD/"waveform_snr.json").write_text(json.dumps(waveform, indent=2)+"\n")
print(f"PASS RTL waveform: {waveform['samples']} samples, expected 20 dB, measured {waveform['measured_db']:.4f} dB")

with (BUILD/"snr_cases.csv").open(newline="") as stream:
    cases = list(csv.DictReader(stream))
signals = {"case_id": (32,"a"), "snr_requested_db": (16,"b"), "snr_active_db": (16,"c"),
           "sigma_q12": (16,"d"), "expected_snr_db_x1000": (32,"e"),
           "measured_snr_db_x1000": (32,"f"), "snr_error_db_x1000": (32,"g"),
           "monitor_update": (1,"h"), "monitor_valid": (1,"i"), "sample_index": (32,"j"),
           "clean_q12": (32,"k"), "noise_q12": (32,"l"), "channel_q12": (32,"m"),
           "measured_signal_power_q24": (64,"n"), "measured_error_power_q24": (64,"o")}
vcd = (BUILD/"snr_monitor.vcd").open("w")
vcd.write("$version Independent monitor of actual Verilator captures $end\n$timescale 1ns $end\n$scope module snr_monitor $end\n")
for name,(width,identifier) in signals.items():
    vcd.write(f"$var wire {width} {identifier} {name} $end\n")
real_aliases = {"expected_snr_db_x1000": ("p", "expected_snr_db"),
                "measured_snr_db_x1000": ("q", "measured_snr_db"),
                "snr_error_db_x1000": ("r", "snr_error_db")}
for identifier,name in real_aliases.values():
    vcd.write(f"$var real 1 {identifier} {name} $end\n")
vcd.write("$upscope $end\n$enddefinitions $end\n")
def emit(time, **changes):
    vcd.write(f"#{time}\n")
    for name,value in changes.items():
        width,identifier = signals[name]
        vcd.write(f"b{int(value)&((1<<width)-1):0{width}b} {identifier}\n")
        if name in real_aliases:
            # Native real-valued VCD traces avoid unsigned display of negative
            # errors and show SNR directly in dB in GTKWave.
            vcd.write(f"r{value/1000:.3f} {real_aliases[name][0]}\n")

results = []
origin = int(cases[0]["first_output_time_ns"])
for case in cases:
    target = int(case["active_db"])
    records = list(struct.iter_unpack("<hhh", (BUILD/case["path"]).read_bytes()))
    if len(records) != int(case["samples"]):
        raise RuntimeError("Truncated SNR capture")
    start = int(case["first_output_time_ns"])-origin
    emit(start,case_id=int(case["case_id"]),snr_requested_db=int(case["requested_db"]),
         snr_active_db=target,sigma_q12=int(case["sigma_q12"]),expected_snr_db_x1000=target*1000,
         measured_snr_db_x1000=0,snr_error_db_x1000=0,monitor_update=0,monitor_valid=0)
    signal_sum = error_sum = noise_sum = clips = 0
    for index,(clean,noise,output) in enumerate(records):
        signal_sum += clean*clean
        error_sum += (output-clean)**2
        noise_sum += noise*noise
        clips += output-clean != noise
        time = start+index*10
        if index < 128:
            emit(time,sample_index=index,clean_q12=clean,noise_q12=noise,channel_q12=output)
        if (index+1)%8192 == 0 or index == len(records)-1:
            measured = 10*math.log10(signal_sum/error_sum)
            emit(time,sample_index=index,clean_q12=clean,noise_q12=noise,channel_q12=output,
                 measured_snr_db_x1000=round(measured*1000),snr_error_db_x1000=round((measured-target)*1000),
                 monitor_update=1,monitor_valid=1,measured_signal_power_q24=round(signal_sum/(index+1)),
                 measured_error_power_q24=round(error_sum/(index+1)))
            emit(time+1,monitor_update=0)
    actual = 10*math.log10(signal_sum/error_sum)
    injected_snr = 10*math.log10(signal_sum/noise_sum)
    expected_sigma = math.sqrt(int(case["reference_power_q24"])/4096**2/10**(target/10))
    expected_quantized_snr = 10*math.log10(
        (int(case["reference_power_q24"])/4096**2)/(int(case["sigma_q12"])/4096)**2)
    if clips or abs(actual-target) > .15 or abs(int(case["sigma_q12"])/4096/expected_sigma-1) > .015:
        raise RuntimeError(f"SNR capture failed: {case}, measured={actual}, clips={clips}")
    result = {"case_id": int(case["case_id"]), "requested_db": int(case["requested_db"]),
              "expected_db": target, "measured_db": actual, "error_db": actual-target,
              "injected_noise_snr_db": injected_snr, "quantized_expected_db": expected_quantized_snr,
              "isi_en": int(case["isi_en"]), "h1": int(case["h1_q12"])/4096,
              "sigma_q12": int(case["sigma_q12"]), "samples": len(records), "clipped_samples": clips,
              "signal_power": signal_sum/len(records)/4096**2,
              "error_power": error_sum/len(records)/4096**2, "status": "PASS"}
    results.append(result)
    print(f"PASS SNR {target:2d} dB, h1={result['h1']:+.2f}, ISI={result['isi_en']}: measured={actual:.5f} dB, error={actual-target:+.5f} dB, clips={clips}")
vcd.close()
report = {"tolerance_db": .15, "waveform": waveform, "cases": results,
          "max_absolute_error_db": max(abs(r["error_db"]) for r in results), "status": "PASS"}
(BUILD/"snr_results.json").write_text(json.dumps(report, indent=2)+"\n")
with (BUILD/"snr_results.csv").open("w", newline="") as stream:
    writer = csv.DictWriter(stream, fieldnames=list(results[0]))
    writer.writeheader(); writer.writerows(results)
print(f"PASS: {len(results)} SNR capture cases; maximum error {report['max_absolute_error_db']:.5f} dB. Monitor waveform: snr_monitor.vcd")
