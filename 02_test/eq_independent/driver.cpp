#include <verilated.h>
#ifdef TEST_FFE
#include "Vrx_ffe.h"
using Dut = Vrx_ffe;
#else
#include "Vrx_dfe.h"
using Dut = Vrx_dfe;
#endif
#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>
#include <cmath>
#include <iomanip>
#include "reference_model.hpp"

using reference::Row;
static void tick(Dut &d) {
    d.i_clk = 0; d.eval(); d.i_clk = 1; d.eval();
}
int main(int argc, char **argv) {
    Verilated::commandArgs(argc, argv);
    const bool generated = argc == 4 && std::string(argv[1]) == "--case";
    if (!generated && argc != 3) {
        std::cerr << "usage: driver --case NAME output_prefix\n"
                     "   or: driver stim.csv actual.csv\n"; return 2;
    }
    try {
        std::vector<Row> rows;
        if (generated) {
#ifdef TEST_FFE
            rows = reference::stimulus(argv[2], true);
#else
            rows = reference::stimulus(argv[2], false);
#endif
        } else {
            std::ifstream in(argv[1]);
            if (!in) throw std::runtime_error("cannot open stimulus");
            std::string line; std::getline(in, line);
            while (std::getline(in, line)) {
                if (line.empty()) continue;
                for (char &c : line) if (c == ',') c = ' ';
                std::istringstream s(line); Row r;
                if (!(s >> r.sample >> r.input >> r.error >> r.lms >> r.enable >> r.mu
                        >> r.w0 >> r.w1 >> r.w2 >> r.b0))
                    throw std::runtime_error("malformed stimulus");
                rows.push_back(r);
            }
        }
        if (rows.empty()) throw std::runtime_error("empty stimulus");
        for (size_t n = 0; n < rows.size(); ++n)
            if (rows[n].sample != int(n)) throw std::runtime_error("non-contiguous sample IDs");
#ifdef TEST_FFE
        const std::vector<std::string> labels{"valid","y","w0","w1","w2"};
        reference::Ffe model(rows.front());
#else
        const std::vector<std::string> labels{"valid","y","b0"};
        reference::Dfe model(rows.front());
#endif
        std::vector<reference::Result> expected;
        std::ofstream diff;
        const std::string prefix = generated ? argv[3] : "";
        std::ofstream io, log;
        const auto report = [&](const std::string &line) {
            std::cout << line << '\n';
            if (log) log << line << '\n';
        };
        if (generated) {
            io.open(prefix + "_io.csv");
            log.open(prefix + "_run.log");
            if (!io || !log) throw std::runtime_error("cannot create IO reports");
#ifdef TEST_FFE
            const std::string block = "FFE";
#else
            const std::string block = "DFE";
#endif
            report("BLOCK=" + block + " CASE=" + argv[2] + " samples=" + std::to_string(rows.size()));
            report(std::string("MODE=") + (rows.front().enable ? (rows.front().lms ? "ADAPTIVE (supplied error)" : "FIXED COEFFICIENTS") : "BYPASS"));
            report("Units: signal/tap raw Q12 / 4096; mu raw Q16 / 65536. SV = RTL simulated by Verilator.");
            report("Timing: y uses taps BEFORE update; reported taps_after use the matching error one edge later.");
            report("Error is supplied by this test, not generated by a slicer; no closed-loop convergence claim.");
            const auto &r = rows.front();
            std::ostringstream config;
            config << "CONFIG enable=" << r.enable << " lms=" << r.lms << " mu=" << r.mu
                   << " (" << double(r.mu)/65536 << ") initial_taps_Q12=";
#ifdef TEST_FFE
            config << '[' << r.w0 << ',' << r.w1 << ',' << r.w2 << ']';
            report("INPUT: x[n], x[n-1], x[n-2]; OUTPUT: filtered y and w0/w1/w2.");
#else
            config << '[' << r.b0 << ']';
            report("INPUT: supplied d_hat[n-1]; OUTPUT: feedback=b0*d_hat[n-1], before subtraction from FFE.");
#endif
            report(config.str());
            report("Preview: first 8 and last 4 samples, plus up to 8 other mismatching samples. Complete data: " + prefix + "_io.csv");
            io << "sample,input_q12,input_real,error_q12,error_real,lms,enable,mu_q16,mu_real";
#ifdef TEST_FFE
            io << ",x_n1_q12,x_n2_q12";
#endif
            for (const auto &label : labels) {
                const std::string field = label == "valid" || label == "y" ? label : label + "_after";
                io << ",cpp_" << field << ",sv_" << field << ",delta_" << field;
                if (label != "valid") io << ",cpp_" << field << "_real,sv_" << field << "_real";
            }
            for (size_t k = 2; k < labels.size(); ++k)
                io << ",cpp_" << labels[k] << "_before_q12,sv_" << labels[k] << "_before_q12";
            io << ",match\n";
            io << std::setprecision(12);
            std::ofstream stim(prefix + "_stim.csv"), gold(prefix + "_expected.csv");
            diff.open(prefix + "_diff.csv");
            if (!stim || !gold || !diff) throw std::runtime_error("cannot create reference reports");
            stim << "sample,input,error,lms,enable,mu,w0,w1,w2,b0\n";
            gold << "sample";
            for (const auto &label : labels) gold << ',' << label;
            gold << '\n';
            diff << "sample,signal,cpp_model,rtl,delta_lsb,delta_real\n";
            diff << std::setprecision(12);
            for (const auto &r : rows) {
                stim << r.sample << ',' << r.input << ',' << r.error << ',' << r.lms << ','
                     << r.enable << ',' << r.mu << ',' << r.w0 << ',' << r.w1 << ','
                     << r.w2 << ',' << r.b0 << '\n';
                const auto value = model.step(r); expected.push_back(value);
                gold << r.sample << ",1," << value.y;
                for (size_t k = 0; k < labels.size()-2; ++k) gold << ',' << value.weights[k];
                gold << '\n';
            }
        }
        std::vector<size_t> counts(labels.size(), 0);
        std::vector<int64_t> maximum(labels.size(), 0);
        std::vector<long double> squared(labels.size(), 0);
        size_t failures = 0;
        Dut d;
        const Row &cfg = rows.front();
        d.i_clk = 0; d.i_rstn = 0; d.i_valid = 0;
        d.i_error = 0; d.i_cfg_lms_en = cfg.lms; d.i_learning_rate = cfg.mu;
#ifdef TEST_FFE
        d.i_r_in = 0; d.i_cfg_ffe_en = cfg.enable;
        d.i_cfg_ffe_w0 = cfg.w0; d.i_cfg_ffe_w1 = cfg.w1; d.i_cfg_ffe_w2 = cfg.w2;
#else
        d.i_sliced_data = 0; d.i_cfg_dfe_en = cfg.enable; d.i_cfg_dfe_b0 = cfg.b0;
        d.i_error_valid = 0;
#endif
        d.eval(); tick(d); tick(d); d.i_rstn = 1;
        std::ofstream out(generated ? prefix + "_actual.csv" : std::string(argv[2]));
        if (!out) throw std::runtime_error("cannot open output");
#ifdef TEST_FFE
        out << "sample,valid,y,w0,w1,w2\n";
#else
        out << "sample,valid,y,b0\n";
#endif
        // Both filters have one sample register. Cache y at acceptance,
        // then read taps one edge later after the matching error update.
        int previous_dfe_y = 0, previous_dfe_valid = 0;
#ifdef TEST_FFE
        std::vector<int64_t> previous_taps{cfg.w0, cfg.w1, cfg.w2};
#else
        std::vector<int64_t> previous_taps{cfg.b0};
#endif
        size_t extra_previews = 0;
        for (size_t cycle = 0; cycle <= rows.size(); ++cycle) {
            d.i_valid = cycle < rows.size();
            d.i_error = cycle ? rows[cycle-1].error : 0;
            const int input = cycle < rows.size() ? rows[cycle].input : 0;
#ifdef TEST_FFE
            d.i_r_in = input;
#else
            d.i_sliced_data = input;
            d.i_error_valid = cycle > 0;
#endif
            tick(d);
#ifdef TEST_FFE
            const int current_dfe_y = int16_t(d.o_ffe_data);
#else
            const int current_dfe_y = int16_t(d.o_dfe_data);
#endif
            const int current_dfe_valid = int(d.o_valid);
            if (!cycle) {
                previous_dfe_y = current_dfe_y; previous_dfe_valid = current_dfe_valid;
                continue;
            }
            const size_t n = cycle-1;
#ifdef TEST_FFE
            const std::vector<int64_t> actual{previous_dfe_valid, previous_dfe_y,
                int16_t(d.o_curr_w0), int16_t(d.o_curr_w1), int16_t(d.o_curr_w2)};
#else
            const std::vector<int64_t> actual{previous_dfe_valid,previous_dfe_y,int16_t(d.o_curr_b0)};
#endif
            previous_dfe_y = current_dfe_y; previous_dfe_valid = current_dfe_valid;
            out << rows[n].sample;
            for (const auto value : actual) out << ',' << value;
            out << '\n';
            if (generated) {
                const auto &r = rows[n];
                io << n << ',' << r.input << ',' << double(r.input)/4096
                   << ',' << r.error << ',' << double(r.error)/4096 << ',' << r.lms
                   << ',' << r.enable << ',' << r.mu << ',' << double(r.mu)/65536;
#ifdef TEST_FFE
                io << ',' << (n ? rows[n-1].input : 0) << ',' << (n > 1 ? rows[n-2].input : 0);
#endif
                bool matches = true;
                for (size_t k = 0; k < labels.size(); ++k) {
                    const int64_t gold = k == 0 ? 1 : (k == 1 ? expected[n].y : expected[n].weights[k-2]);
                    const int64_t delta = actual[k] - gold;
                    io << ',' << gold << ',' << actual[k] << ',' << delta;
                    if (k) io << ',' << double(gold)/4096 << ',' << double(actual[k])/4096;
                    matches = matches && delta == 0;
                    const int64_t absolute = delta < 0 ? -delta : delta;
                    maximum[k] = std::max(maximum[k], absolute);
                    squared[k] += static_cast<long double>(delta) * delta;
                    if (!delta) continue;
                    if (!failures)
                        std::cout << "FIRST FAIL sample=" << n << " signal=" << labels[k]
                                  << " C++model=" << gold << " RTL=" << actual[k] << " delta=" << delta << '\n';
                    ++failures; ++counts[k];
                    diff << n << ',' << labels[k] << ',' << gold << ',' << actual[k] << ',' << delta << ',';
                    if (k) diff << double(delta)/4096;
                    diff << '\n';
                }
                for (size_t k = 2; k < labels.size(); ++k) {
                    const int64_t before = n ? expected[n-1].weights[k-2] : previous_taps[k-2];
                    io << ',' << before << ',' << previous_taps[k-2];
                }
                io << ',' << (matches ? "PASS" : "FAIL") << '\n';
                const bool preview = n < 8 || n + 4 >= rows.size();
                if (preview || (!matches && extra_previews < 8)) {
                    if (!preview) ++extra_previews;
                    std::ostringstream line;
                    line << std::setprecision(8) << "sample=" << n << " input=" << r.input
                         << " (" << double(r.input)/4096 << ") error=" << r.error
                         << " (" << double(r.error)/4096 << ')';
#ifdef TEST_FFE
                    line << " x_history_Q12=[" << r.input << ',' << (n ? rows[n-1].input : 0)
                         << ',' << (n > 1 ? rows[n-2].input : 0) << ']';
#endif
                    for (size_t k = 0; k < labels.size(); ++k) {
                        const int64_t gold = k == 0 ? 1 : (k == 1 ? expected[n].y : expected[n].weights[k-2]);
                        if (k > 1) {
                            const int64_t before = n ? expected[n-1].weights[k-2] : previous_taps[k-2];
                            line << ' ' << labels[k] << "_before(C++/SV)=" << before << '/' << previous_taps[k-2];
                        }
                        line << ' ' << labels[k] << (k > 1 ? "_after" : "") << "(C++/SV)=" << gold << '/' << actual[k];
                        if (k) line << " (" << double(gold)/4096 << '/' << double(actual[k])/4096 << ')';
                    }
                    line << ' ' << (matches ? "PASS" : "FAIL");
                    report(line.str());
                }
                for (size_t k = 2; k < labels.size(); ++k) previous_taps[k-2] = actual[k];
            }
        }
        d.final();
        if (generated) {
            for (size_t k = 0; k < labels.size(); ++k) {
                std::ostringstream line;
                line << labels[k] << ": mismatches=" << counts[k] << '/' << rows.size()
                          << " max_abs=" << maximum[k] << " RMSE="
                          << double(std::sqrt(squared[k]/rows.size())) << " [raw integer/LSB]";
                report(line.str());
            }
            report(std::string(failures ? "FAIL" : "PASS") + " differences=" + std::to_string(failures)
                   + " diff=" + prefix + "_diff.csv log=" + prefix + "_run.log");
        }
        return failures ? 1 : 0;
    } catch (const std::exception &e) { std::cerr << e.what() << '\n'; return 2; }
    return 0;
}
